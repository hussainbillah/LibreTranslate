// Builds src/assets/map.js: world land + Bangladesh outline as SVG paths, from
// Natural Earth data (world-atlas, public domain). Run once; output is committed.
//   (cd tools && npm i world-atlas@2.0.2 topojson-client@3.1.0 d3-geo@3.1.1) && node tools/build_map.mjs
import { readFileSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
const require = createRequire(import.meta.url);
const topo = require("topojson-client");
const d3 = require("d3-geo");
const land = topo.feature(JSON.parse(readFileSync(require.resolve("world-atlas/land-110m.json"))), "land");
const c50 = JSON.parse(readFileSync(require.resolve("world-atlas/countries-50m.json")));
const bd = topo.feature(c50, c50.objects.countries).features.find((f) => f.id === "050");
if (!bd) throw new Error("Bangladesh (050) not found");
const W = 1600, H = 820;
const proj = d3.geoNaturalEarth1().fitExtent([[10, 10], [W - 10, H - 10]], { type: "Sphere" });
const path = d3.geoPath(proj);
// City nodes for the "connected to the global digital economy" motif (illustrative).
const cities = { dhaka: [90.41, 23.81], singapore: [103.82, 1.35], frankfurt: [8.68, 50.11], london: [-0.13, 51.5], virginia: [-77.5, 39.0], tokyo: [139.69, 35.69], mumbai: [72.88, 19.08], dubai: [55.27, 25.2], sydney: [151.2, -33.87], saopaulo: [-46.63, -23.55] };
const pts = Object.fromEntries(Object.entries(cities).map(([k, v]) => [k, proj(v).map((n) => +n.toFixed(1))]));
// Zoomed Bangladesh for scene close-ups.
const projBD = d3.geoMercator().fitExtent([[20, 20], [580, 680]], bd);
const out = { W, H, land: path(land), bd: path(bd), bdBox: path.bounds(bd), cities: pts, bdZoom: d3.geoPath(projBD)(bd), dhakaZoom: projBD(cities.dhaka) };
writeFileSync(new URL("../src/assets/map.js", import.meta.url), "// Generated by tools/build_map.mjs from Natural Earth (public domain) via world-atlas.\nwindow.MAP = " + JSON.stringify(out) + ";\n");
console.log("map.js", JSON.stringify(out).length, "bytes; dhaka", pts.dhaka, "bdBox", out.bdBox);
