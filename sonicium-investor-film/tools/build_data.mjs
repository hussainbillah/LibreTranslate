// Recomputes every derived number shown on screen from
// sonicium_entropy_financial_model.json and writes src/data.js (window.DATA).
//
//   node tools/build_data.mjs
//
// Revenue per scenario and year (year-end annual run-rate):
//   subscriptions = (professional × $29 + business × $199) × 12 × (1 + usage uplift)
//   enterprise    = contracts × ACV assumption
//   integrations  = projects × fee assumption
//   + partner channel + research access (assumptions)
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const M = JSON.parse(readFileSync(join(ROOT, "sonicium_entropy_financial_model.json"), "utf8"));
const P = M.pricing;
const years = M.scenarios.years;

const scenarios = {};
for (const key of ["conservative", "base", "growth"]) {
  const s = M.scenarios[key];
  scenarios[key] = years.map((year, i) => {
    const subs = (s.professional_customers[i] * P.professional.usd_per_month + s.business_customers[i] * P.business.usd_per_month) * 12 * (1 + s.usage_overage_uplift_assumption);
    const enterprise = s.enterprise_contracts[i] * s.enterprise_acv_usd_assumption;
    const integrations = s.integration_projects[i] * s.integration_fee_usd_assumption;
    const other = s.partner_channel_usd_assumption[i] + s.research_access_usd_assumption[i];
    return { year, subs: Math.round(subs), enterprise, integrations, other, total: Math.round(subs + enterprise + integrations + other) };
  });
}

const tam = M.tam_sam_som.tam_usd;
const sam = tam * M.tam_sam_som.sam_share_of_tam_assumption;
const som = scenarios[M.tam_sam_som.som_from_scenario].at(-1).total;
const data = {
  market: M.market,
  shares: M.share_scenarios.shares.map((share) => ({ share, usd: M.share_scenarios.reference_market_usd * share })),
  shareLabel: M.share_scenarios._label,
  tam, sam, som,
  samShare: M.tam_sam_som.sam_share_of_tam_assumption,
  somShareOfSam: som / sam,
  somShareOfTam: som / tam,
  pricing: P,
  scenarios,
  roadmap: M.roadmap_targets.phases,
};
writeFileSync(join(ROOT, "src/data.js"), `// Generated by tools/build_data.mjs from sonicium_entropy_financial_model.json. Do not edit by hand.\nwindow.DATA = ${JSON.stringify(data, null, 1)};\n`);
for (const k in scenarios) console.log(k.padEnd(13), scenarios[k].map((r) => `${r.year}: $${(r.total / 1e3).toFixed(0)}k`).join("  "));
console.log(`TAM $${(tam / 1e9).toFixed(2)}B · SAM (assumption ${M.tam_sam_som.sam_share_of_tam_assumption * 100}%) $${(sam / 1e6).toFixed(0)}M · SOM (base 2030 run-rate) $${(som / 1e6).toFixed(2)}M = ${(data.somShareOfTam * 100).toFixed(3)}% of TAM`);
