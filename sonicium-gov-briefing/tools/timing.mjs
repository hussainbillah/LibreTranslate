// Generates src/timing.js — the start/end of every narration cue.
//
//   node tools/timing.mjs                          # estimate from narration length
//   node tools/timing.mjs --voice output/voiceover.mp3   # measure from a recorded voice-over
//
// Scene bounds are fixed by the storyboard (src/script.js). With --voice, the
// voice-over's sentence pauses (ffmpeg silencedetect) are aligned to the cues
// by length with a monotone dynamic-programming match, and any cue that would
// spill out of its scene is reported so the narration can be re-recorded or
// the scene text shortened.
import { execFileSync } from "node:child_process";
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import vm from "node:vm";

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const ctx = {};
vm.runInNewContext(readFileSync(join(ROOT, "src/script.js"), "utf8"), ctx);
const S = ctx.SCRIPT;
const args = process.argv.slice(2);
const voice = args.includes("--voice") ? args[args.indexOf("--voice") + 1] : null;

// Speaking rate measured on the earlier ElevenLabs Bengali narration:
// 0.0855 s per letter (spaces and punctuation excluded), ~0.45 s per sentence pause.
const RATE = 0.0855, PAUSE = 0.45, LINGER = 0.3;
const letters = (t) => [...t.replace(/[\s—,।:;.\-]/g, "")].length;

const flat = S.scenes.flatMap((sc, si) => sc.cues.map((text) => ({ si, text, L: letters(text) })));
let cues = [];
const report = [];

if (!voice) {
  for (const [si, sc] of S.scenes.entries()) {
    const mine = flat.filter((c) => c.si === si);
    const lead = si === 0 ? 1.6 : 1.0, tail = si === S.scenes.length - 1 ? 4.0 : 1.2;
    const avail = sc.end - sc.start - lead - tail;
    const need = mine.reduce((n, c) => n + c.L * RATE, 0) + PAUSE * (mine.length - 1);
    const scale = Math.min(1, avail / need);
    const slack = Math.max(0, avail - need);
    let t = sc.start + lead;
    for (const c of mine) {
      const d = c.L * RATE * scale;
      cues.push([t, t + d]);
      t += d + PAUSE * scale + slack / mine.length;
    }
    report.push(`${sc.id.padEnd(10)} ${sc.end - sc.start}s  speech ${need.toFixed(1)}s  fill ${((need / (sc.end - sc.start)) * 100).toFixed(0)}%${scale < 1 ? `  COMPRESSED x${scale.toFixed(2)}` : ""}`);
  }
} else {
  const err = execFileSync("sh", ["-c", `ffmpeg -hide_banner -i "${voice}" -af silencedetect=noise=-35dB:d=0.3 -f null - 2>&1`], { encoding: "utf8" });
  const dur = Number(execFileSync("ffprobe", ["-v", "error", "-show_entries", "format=duration", "-of", "csv=p=0", voice], { encoding: "utf8" }));
  const ss = [...err.matchAll(/silence_start: ([\d.]+)/g)].map((m) => +m[1]);
  const se = [...err.matchAll(/silence_end: ([\d.]+)/g)].map((m) => +m[1]);
  const segs = [];
  let cur = 0;
  for (let i = 0; i < ss.length; i++) { if (ss[i] - cur > 0.15) segs.push([cur, ss[i]]); cur = se[i] ?? dur; }
  if (dur - cur > 0.15) segs.push([cur, dur]);
  if (segs.length < flat.length) throw new Error(`voice has ${segs.length} speech blocks but the script has ${flat.length} cues`);
  const D = segs.map(([a, b]) => b - a);
  const rate = D.reduce((a, b) => a + b, 0) / flat.reduce((a, c) => a + c.L, 0);
  const n = flat.length, m = segs.length, memo = new Map();
  const f = (i, j) => {
    if (i === n) return j === m ? [0, []] : [Infinity, []];
    const key = i * 10000 + j;
    if (memo.has(key)) return memo.get(key);
    let best = [Infinity, []], acc = 0;
    for (let k = j + 1; k <= m - (n - i - 1); k++) {
      acc += D[k - 1];
      const exp = flat[i].L * rate, e = ((acc - exp) / exp) ** 2;
      const r = f(i + 1, k);
      if (r[0] + e < best[0]) best = [r[0] + e, [[j, k], ...r[1]]];
    }
    memo.set(key, best);
    return best;
  };
  const [, asg] = f(0, 0);
  cues = asg.map(([j, k]) => [segs[j][0], segs[k - 1][1]]);
  cues.forEach(([a, b], i) => {
    const sc = S.scenes[flat[i].si];
    if (a < sc.start || b > sc.end) report.push(`WARNING cue ${i + 1} (${a.toFixed(1)}–${b.toFixed(1)}s) falls outside scene "${sc.id}" ${sc.start}–${sc.end}s`);
  });
  report.push(`voice ${dur.toFixed(1)}s, ${segs.length} speech blocks → ${n} cues, ${rate.toFixed(4)} s/letter`);
}

// Subtitle display window: lead in slightly, linger a little, never overlap
// the next cue or cross the scene end.
const out = cues.map(([a, b], i) => {
  const sc = S.scenes[flat[i].si];
  const next = cues[i + 1]?.[0] ?? S.duration;
  const s = Math.max(sc.start, a - 0.1);
  const e = Math.min(b + LINGER, next - 0.12, sc.end - 0.1);
  return [+s.toFixed(2), +e.toFixed(2)];
});
writeFileSync(join(ROOT, "src/timing.js"), `// Generated by tools/timing.mjs (${voice ? "measured from " + voice.split("/").pop() : "estimated from narration length"}). Do not edit by hand.\nwindow.TIMING = ${JSON.stringify({ source: voice ? "voice" : "estimate", cues: out })};\n`);
console.log(report.join("\n"));
console.log(`wrote src/timing.js (${out.length} cues)`);
