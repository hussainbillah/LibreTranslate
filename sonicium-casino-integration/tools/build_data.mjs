// Recomputes the ROI calculator from sonicium_entropy_roi_calculator.json and
// writes src/data.js (window.DATA) for the video. Fails if the sample inputs
// no longer produce the expected sample outputs, so an edit to the formulas
// cannot silently change the numbers on screen.
//
//   node tools/build_data.mjs
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const R = JSON.parse(readFileSync(join(ROOT, "sonicium_entropy_roi_calculator.json"), "utf8"));
const i = R.inputs;

const monthlyRecurring = i.monthly_service_fee_usd + i.monthly_operating_cost_usd;
const firstYearCost = i.initial_integration_cost_usd + 12 * monthlyRecurring;
const firstYearRequests = 12 * i.monthly_api_requests;
const costPerMillion = firstYearCost / (firstYearRequests / 1e6);
const annualBenefit = 12 * i.monthly_measurable_benefit_usd;
const netBenefit = annualBenefit - firstYearCost;
const roi = (netBenefit / firstYearCost) * 100;

const out = {
  monthly_recurring_cost: monthlyRecurring,
  first_year_total_cost: firstYearCost,
  first_year_requests: firstYearRequests,
  cost_per_million_requests: +costPerMillion.toFixed(2),
  annual_measurable_benefit: annualBenefit,
  net_first_year_benefit: netBenefit,
  first_year_roi_percent: +roi.toFixed(2),
};

const sample = { monthly_api_requests: 10000000, monthly_service_fee_usd: 500, initial_integration_cost_usd: 2000, monthly_operating_cost_usd: 100, monthly_measurable_benefit_usd: 1000 };
if (JSON.stringify(sample) === JSON.stringify(i)) {
  for (const [k, v] of Object.entries(R.outputs_expected_for_sample)) {
    if (Math.abs(out[k] - v) > 0.01) throw new Error(`${k}: computed ${out[k]}, expected ${v}`);
  }
}

// Monthly cumulative cost vs cumulative benefit, for the chart.
const months = Array.from({ length: 13 }, (_, m) => ({
  m,
  cost: m === 0 ? i.initial_integration_cost_usd : i.initial_integration_cost_usd + m * monthlyRecurring,
  benefit: m * i.monthly_measurable_benefit_usd,
}));
const breakEvenMonth = months.find((r) => r.m > 0 && r.benefit >= r.cost)?.m ?? null;

writeFileSync(join(ROOT, "src/data.js"), `// Generated by tools/build_data.mjs from sonicium_entropy_roi_calculator.json. Do not edit by hand.\nwindow.DATA = ${JSON.stringify({ label: R._label, inputs: i, out, months, breakEvenMonth, catalog: R.catalog_context }, null, 1)};\n`);
console.log(out, "break-even month:", breakEvenMonth);
